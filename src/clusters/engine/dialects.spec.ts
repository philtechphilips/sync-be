import { ClusterType } from '../entities/cluster.entity';
import { dialectFor, matchKey, toPgArrayLiteral } from './dialects';
import { ColumnInfo, ValueKind } from './types';

const col = (
  name: string,
  kind: ValueKind,
  extra: Partial<ColumnInfo> = {},
): ColumnInfo => ({
  schema: null,
  table: 't',
  tableName: 't',
  name,
  type: kind === 'text' ? 'varchar' : kind,
  fullType: kind === 'text' ? 'varchar(20)' : kind,
  nullable: 'YES',
  defaultValue: null,
  columnKey: '',
  isAutoIncrement: false,
  isGenerated: false,
  generationExpression: null,
  onUpdate: null,
  referencedTable: null,
  referencedColumn: null,
  ordinal: 1,
  kind,
  ...extra,
});

const T = { schema: null, table: 't' };

describe('dialects', () => {
  it('quotes identifiers per engine', () => {
    expect(dialectFor(ClusterType.MYSQL).quote('a`b')).toBe('`a``b`');
    expect(dialectFor(ClusterType.POSTGRES).quote('a"b')).toBe('"a""b"');
    expect(dialectFor(ClusterType.MSSQL).quote('a]b')).toBe('[a]]b]');
  });

  it('writes literals that cannot break out of strings', () => {
    const mysql = dialectFor(ClusterType.MYSQL);
    expect(mysql.literal("\\'); DROP TABLE x; --", col('c', 'text'))).toBe(
      "'\\\\\\'); DROP TABLE x; --'",
    );
    expect(mysql.literal({ a: "o'k" }, col('j', 'json'))).toBe(
      `'{\\"a\\":\\"o\\'k\\"}'`,
    );
    expect(mysql.literal('0xdead', col('b', 'binary'))).toBe("X'dead'");
    expect(
      dialectFor(ClusterType.POSTGRES).literal('0xdead', col('b', 'binary')),
    ).toBe("decode('dead', 'hex')");
    expect(dialectFor(ClusterType.MSSQL).literal("o'k", col('c', 'text'))).toBe(
      "N'o''k'",
    );
    expect(
      dialectFor(ClusterType.POSTGRES).literal(1, col('f', 'boolean')),
    ).toBe('TRUE');
    expect(
      dialectFor(ClusterType.POSTGRES).literal('123.45', col('n', 'decimal')),
    ).toBe('123.45');
  });

  it('builds Postgres array literals', () => {
    expect(toPgArrayLiteral(['a"b', null, 'c\\d'])).toBe(
      '{"a\\"b",NULL,"c\\\\d"}',
    );
  });

  it('creates tables with composite keys and identity columns per engine', () => {
    const columns = [
      col('a', 'integer', {
        columnKey: 'PRI',
        isAutoIncrement: true,
        nullable: 'NO',
        ordinal: 1,
      }),
      col('b', 'text', { columnKey: 'PRI', nullable: 'NO', ordinal: 2 }),
      col('data', 'json', { ordinal: 3 }),
    ];
    const pg = dialectFor(ClusterType.POSTGRES).createTable(
      T,
      columns,
      ClusterType.MYSQL,
    );
    expect(pg).toContain(
      '"a" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL',
    );
    expect(pg).toContain('PRIMARY KEY ("a", "b")');
    expect(pg).toContain('"data" jsonb');
    const ms = dialectFor(ClusterType.MSSQL).createTable(
      T,
      columns,
      ClusterType.MYSQL,
    );
    expect(ms).toMatch(
      /^IF OBJECT_ID\(N'\[t\]', N'U'\) IS NULL CREATE TABLE \[t\]/,
    );
    expect(ms).toContain('[a] int IDENTITY(1,1) NOT NULL');
    expect(ms).toContain('[b] nvarchar(20) NOT NULL');
  });

  it('limits key-less updates to one row', () => {
    expect(
      dialectFor(ClusterType.MYSQL).updateOne(T, 'a = ?', 'b = ?'),
    ).toMatch(/LIMIT 1$/);
    expect(dialectFor(ClusterType.POSTGRES).deleteOne(T, 'b = $1')).toContain(
      'ctid = (SELECT ctid',
    );
    expect(
      dialectFor(ClusterType.MSSQL).updateOne(T, 'a = @p1', 'b = @p2'),
    ).toMatch(/^UPDATE TOP \(1\)/);
  });

  it('qualifies tables outside the default schema', () => {
    const pg = dialectFor(ClusterType.POSTGRES);
    expect(pg.displayName({ schema: 'public', table: 'users' })).toBe('users');
    expect(pg.displayName({ schema: 'sales', table: 'orders' })).toBe(
      'sales.orders',
    );
    expect(pg.qualify({ schema: 'sales', table: 'or"ders' })).toBe(
      '"sales"."or""ders"',
    );
    expect(
      dialectFor(ClusterType.MSSQL).displayName({ schema: 'dbo', table: 'x' }),
    ).toBe('x');
  });

  it('matches tables across engines by schema only when both have schemas', () => {
    const pg = dialectFor(ClusterType.POSTGRES);
    const ms = dialectFor(ClusterType.MSSQL);
    expect(matchKey(pg, { schema: 'public', table: 'a' }, true)).toBe(
      matchKey(ms, { schema: 'dbo', table: 'a' }, true),
    );
    expect(matchKey(pg, { schema: 'sales', table: 'a' }, true)).toBe('sales.a');
    expect(matchKey(pg, { schema: 'sales', table: 'a' }, false)).toBe('a');
  });
});
